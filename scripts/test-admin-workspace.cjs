'use strict';
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const workspace = require('../development/source/admin/workspace');
const mobile = require('../development/source/admin/mobile');

const shell = `<div class="admin-shell"><header class="admin-topbar"><a class="admin-logo-button" href="/">BE</a><nav class="admin-nav"><button data-route="dashboard" class="active">Início</button><button data-route="users">Pessoas</button></nav><div class="admin-account"><div class="admin-avatar-button">M</div></div></header><main class="admin-main"><nav class="admin-subnav" hidden></nav><section class="admin-content" id="adminContent"><h1>Visão geral</h1><button id="original-action">Editar</button></section></main></div>`;
const dom = new JSDOM(`<body class="admin-mode">${shell}</body>`, { url: 'https://betv.test/admin#/admin/dashboard', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window, d = w.document;
const settle = () => new Promise(resolve => w.setTimeout(resolve, 10));
(async () => {
  let edits = 0;
  d.getElementById('original-action').onclick = () => edits++;
  w.eval(mobile); w.eval(workspace);
  assert(d.querySelector('.workspace-brand'));
  assert.equal(d.querySelectorAll('.workspace-bar').length, 1);
  assert.equal(d.querySelector('.workspace-context strong').textContent, 'Visão geral');
  d.getElementById('original-action').click(); assert.equal(edits, 1);
  const trigger = d.querySelector('.workspace-search'); trigger.focus(); trigger.click();
  const dialog = d.querySelector('[role="dialog"]');
  assert.equal(dialog.getAttribute('aria-modal'), 'true');
  assert.equal(d.activeElement.tagName, 'INPUT');
  const input = dialog.querySelector('input');
  input.value = 'albuns'; input.dispatchEvent(new w.Event('input', { bubbles: true }));
  assert.equal(dialog.querySelectorAll('.workspace-command-results button').length, 1);
  assert.match(dialog.textContent, /Álbuns/);
  input.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  await settle(); assert.equal(w.location.hash, '#/admin/contents/news');
  assert.equal(d.querySelector('.workspace-command').hidden, true);
  assert.equal(d.activeElement, trigger, 'dismissal restores focus');
  assert.equal(d.querySelector('.workspace-context strong').textContent, 'Álbuns');
  d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'k', ctrlKey: true, bubbles: true }));
  assert.equal(d.querySelector('.workspace-command').hidden, false);
  input.value = '<script>'; input.dispatchEvent(new w.Event('input', { bubbles: true }));
  assert(dialog.querySelector('.workspace-command-empty'));
  assert(!dialog.querySelector('script'));
  input.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert.equal(d.querySelector('.workspace-command').hidden, true);
  // Async page replacements must not duplicate chrome or drop mobile controls.
  d.querySelector('.admin-shell').outerHTML = shell;
  await settle();
  assert.equal(d.querySelectorAll('.workspace-bar').length, 1);
  assert(d.querySelector('.admin-mobile-tabs'));
  assert.equal(d.querySelectorAll('.workspace-brand').length, 1);
  w.eval(workspace); await settle();
  assert.equal(d.querySelectorAll('#betv-admin-workspace').length, 1);
  d.querySelector('.workspace-search').click();
  const close = d.querySelector('.workspace-command-close'); close.focus();
  close.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true }));
  assert.equal(d.activeElement, d.querySelector('.workspace-command-results').lastElementChild, 'dialog traps keyboard focus');
  d.body.innerHTML = '<div class="admin-login">Entrar</div>';
  await settle();
  assert.equal(d.querySelector('.workspace-command'), null, 'admin navigation cannot remain on the login screen');
  assert(d.getElementById('betv-admin-workspace').sheet.cssRules.length > 0);
  console.log('PASS admin workspace: preserved actions, command search, accent matching, keyboard/focus, route changes, replacement shell, mobile dock and login cleanup');
})().finally(() => w.close()).catch(error => { console.error(error); process.exitCode = 1; });
